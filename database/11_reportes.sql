PROMPT ===== 01. VENTAS POR PERIODO =====
SELECT V.TIPO_PAGO,
       COUNT(*)              AS CANTIDAD_PEDIDOS,
       SUM(V.TOTAL)          AS TOTAL_VENDIDO,
       SUM(V.CAMBIO)         AS TOTAL_CAMBIO
  FROM VW_VENTAS_POR_PEDIDO V
 WHERE V.ESTADO IN ('PAGADO', 'ENTREGADO')
   AND V.ESTADO_PAGO = 'APROBADO'
   AND V.FECHA_PEDIDO BETWEEN DATE '2026-01-01' AND DATE '2026-12-31'
 GROUP BY V.TIPO_PAGO
 ORDER BY V.TIPO_PAGO;

PROMPT ===== 01b. VENTAS POR PERIODO (TOTAL GENERAL) =====
SELECT COUNT(*)     AS CANTIDAD_PEDIDOS,
       NVL(SUM(V.TOTAL), 0) AS TOTAL_VENDIDO,
       NVL(SUM(CASE WHEN V.TIPO_PAGO = 'EFECTIVO' THEN V.TOTAL END), 0) AS TOTAL_EFECTIVO,
       NVL(SUM(CASE WHEN V.TIPO_PAGO = 'TARJETA'  THEN V.TOTAL END), 0) AS TOTAL_TARJETA
  FROM VW_VENTAS_POR_PEDIDO V
 WHERE V.ESTADO IN ('PAGADO', 'ENTREGADO')
   AND V.ESTADO_PAGO = 'APROBADO'
   AND V.FECHA_PEDIDO BETWEEN DATE '2026-01-01' AND DATE '2026-12-31';

PROMPT ===== 02. PRODUCTOS MAS VENDIDOS =====
SELECT VU.CODIGO,
       VU.NOMBRE,
       VU.CATEGORIA,
       VU.ORIGEN,
       VU.UNIDADES,
       VU.IMPORTE
  FROM VW_VENTAS_UNIDADES VU
 ORDER BY VU.UNIDADES DESC, VU.NOMBRE;

PROMPT ===== 02b. PRODUCTOS MAS VENDIDOS (CONSOLIDADO) =====
SELECT VU.CODIGO,
       VU.NOMBRE,
       VU.CATEGORIA,
       SUM(VU.UNIDADES) AS UNIDADES,
       SUM(VU.IMPORTE)  AS IMPORTE
  FROM VW_VENTAS_UNIDADES VU
 GROUP BY VU.CODIGO, VU.NOMBRE, VU.CATEGORIA
 ORDER BY UNIDADES DESC;

