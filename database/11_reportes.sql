PROMPT ===== 05. HISTORIAL DE CANJES =====
SELECT CA.ID_CANJE,
       CA.FECHA_CANJE,
       C.DPI,
       C.NOMBRE,
       R.CODIGO AS RECOMPENSA,
       R.NOMBRE AS NOMBRE_RECOMPENSA,
       CA.PUNTOS_USADOS
  FROM CANJE CA
  JOIN CLIENTE C    ON C.ID_CLIENTE = CA.ID_CLIENTE
  JOIN RECOMPENSA R ON R.ID_RECOMPENSA = CA.ID_RECOMPENSA
 ORDER BY CA.FECHA_CANJE DESC, CA.ID_CANJE DESC;

PROMPT ===== 06. VENTAS DE MENUS COMPLETOS =====
SELECT M.CODIGO,
       M.NOMBRE,
       SUM(DP.CANTIDAD)  AS CANTIDAD,
       SUM(DP.SUBTOTAL) AS IMPORTE,
       SUM(DP.PUNTOS)   AS PUNTOS
  FROM DETALLE_PEDIDO DP
  JOIN PEDIDO PE ON PE.ID_PEDIDO = DP.ID_PEDIDO
  JOIN MENU M    ON M.ID_MENU = DP.ID_MENU
 WHERE DP.TIPO_ITEM = 'MENU'
   AND PE.ESTADO IN ('PAGADO', 'ENTREGADO')
   AND PE.FECHA_PEDIDO BETWEEN DATE '2026-01-01' AND DATE '2026-12-31'
 GROUP BY M.CODIGO, M.NOMBRE
 ORDER BY CANTIDAD DESC;

PROMPT ===== 07. HISTORIAL DE MOVIMIENTOS DE PUNTOS =====
SELECT MP.FECHA_MOVIMIENTO,
       C.DPI,
       C.NOMBRE,
       MP.TIPO_MOVIMIENTO,
       MP.PUNTOS,
       MP.SALDO_RESULTANTE,
       MP.REFERENCIA
  FROM MOVIMIENTO_PUNTOS MP
  JOIN CLIENTE C ON C.ID_CLIENTE = MP.ID_CLIENTE
 WHERE C.DPI = '12345678-1'
 ORDER BY MP.FECHA_MOVIMIENTO, MP.ID_MOVIMIENTO;

PROMPT ===== 08. HISTORIAL DE MOVIMIENTOS DE INVENTARIO =====
SELECT MI.FECHA_MOVIMIENTO,
       P.CODIGO,
       P.NOMBRE,
       MI.TIPO_MOVIMIENTO,
       MI.CANTIDAD,
       MI.EXISTENCIA_ANTERIOR,
       MI.EXISTENCIA_NUEVA,
       MI.REFERENCIA
  FROM MOVIMIENTO_INVENTARIO MI
  JOIN PRODUCTO P ON P.ID_PRODUCTO = MI.ID_PRODUCTO
 ORDER BY MI.FECHA_MOVIMIENTO DESC, MI.ID_MOVIMIENTO DESC;
